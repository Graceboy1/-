"""Explicit, local-only import of authorized Livermore evidence JSON.

This command has no HTTP client, web upload, credential access, account access,
or order calls. Provenance fields must already have been supplied by the data
owner. Structural validation is not proof of a vendor license or real fills.
No sample 'verified' facts are generated by this tool.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from server import livermore_data, market_history  # noqa: E402


class ImportValidationError(ValueError):
    """Rejected explicit input; never echoed with its potentially secret body."""


def validate_target(code: str) -> None:
    try:
        livermore_data._code(code)
        case = market_history.load_case("history-20261113-" + code)
        name = case.get("name")
        if case.get("symbol") != code or not isinstance(name, str) or not name.strip() or "ST" in name.upper() or "退" in name:
            raise ValueError("Invalid public archive identity")
    except Exception as exc:
        raise ImportValidationError("股票不在当前已校验的主板非ST、非退市历史档案中，拒绝导入。") from exc


def read_input(filename: str) -> dict:
    if not isinstance(filename, str) or re.match(r"^[A-Za-z][A-Za-z0-9+.-]*://", filename) or filename.startswith(("\\\\", "//")):
        raise ImportValidationError("只接受明确指定的本机JSON文件，不支持URL或网络共享路径。")
    path = Path(filename)
    if path.suffix.lower() != ".json" or not path.is_file():
        raise ImportValidationError("未找到本机JSON文件；不读取环境配置或凭据文件。")
    if path.stat().st_size > livermore_data.MAX_PROFILE_BYTES:
        raise ImportValidationError("输入JSON超过允许的单股证据大小。")
    with path.open("rb") as stream:
        raw = stream.read(livermore_data.MAX_PROFILE_BYTES + 1)
    if len(raw) > livermore_data.MAX_PROFILE_BYTES:
        raise ImportValidationError("输入JSON超过允许的单股证据大小。")
    try:
        value = json.loads(raw)
    except (ValueError, UnicodeError, RecursionError) as exc:
        raise ImportValidationError("输入不是有效JSON；未保存任何证据。") from exc
    if not isinstance(value, dict):
        raise ImportValidationError("证据JSON最外层必须为对象。")
    return value


def validate_import(code: str, value: dict) -> dict:
    """Mirror save_profile's pure checks, reusing its actual record validator.

The backend currently exposes no separate validate_profile function. The
formal write is nevertheless always performed by backend.save_profile, which
independently repeats these checks and commits its checksum index.
"""
    try:
        livermore_data._code(code)
        if not isinstance(value, dict) or set(value) != {"schema", "code", "records"} or value.get("schema") != livermore_data.SCHEMA or value.get("code") != code:
            raise ValueError("Invalid profile schema/identity")
        records = value.get("records")
        if not isinstance(records, dict) or set(records) - set(livermore_data.GROUPS):
            raise ValueError("Invalid record groups")
        clean = {}
        for group in livermore_data.GROUPS:
            rows = records.get(group, [])
            if not isinstance(rows, list) or len(rows) > livermore_data.MAX_RECORDS:
                raise ValueError("Oversized evidence group")
            accepted = [livermore_data._validate_record(group, row, code) for row in rows]
            if len({row["date"] for row in accepted}) != len(accepted):
                raise ValueError("Duplicate evidence dates/versions")
            clean[group] = sorted(accepted, key=lambda row: row["date"])
        if not any(clean.values()):
            raise ValueError("Empty evidence would replace the existing profile")
        safe = {"schema": livermore_data.SCHEMA, "code": code, "records": clean}
        if len(livermore_data._canonical(safe)) > livermore_data.MAX_PROFILE_BYTES:
            raise ValueError("Oversized canonical evidence profile")
        return safe
    except (ValueError, TypeError, KeyError, ArithmeticError, RecursionError) as exc:
        raise ImportValidationError("证据字段、日期、单位、来源或证券代码未通过原席位校验；未保存。") from exc


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, help="Existing local authorized evidence JSON; no download or template generation")
    parser.add_argument("--code", required=True, help="Explicit six-digit code in the installed public main-board archive")
    parser.add_argument("--dry-run", action="store_true", help="Validate without creating directories, evidence files or indexes")
    args = parser.parse_args(argv)
    validate_target(args.code)
    safe = validate_import(args.code, read_input(args.input))
    if not args.dry_run:
        safe = livermore_data.save_profile(args.code, safe)
    print(json.dumps({"status": "validated_not_saved" if args.dry_run else "saved", "dry_run": args.dry_run,
                      "schema": safe["schema"], "code": args.code,
                      "record_counts": {group: len(rows) for group, rows in safe["records"].items()},
                      "profile_sha256": hashlib.sha256(livermore_data._canonical(safe)).hexdigest(),
                      "notice": "仅校验结构与本地指纹，不证明来源授权、排队成交或策略收益；本命令不执行交易。"}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ImportValidationError, OSError, ValueError) as exc:
        print(f"利弗莫尔本地证据导入失败：{exc}", file=sys.stderr)
        raise SystemExit(1)
